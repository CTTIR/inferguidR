spec <- function(d=.5) analysis_spec('t_means_one_sample','post_hoc',inputs=list(d=d,alpha=.05,n_total=30),options=list(tails='two'))
a<-spec(); b<-spec(.7); ra<-calculate_power(a); rb<-calculate_power(b)
test_that('drafts and previews do not commit or alter the accepted result',{
 s<-.ig_workbench_new(a,'session-one');s<-.ig_workbench_accept(s,s$pending,ra)
 d<-.ig_workbench_edit(s,list(d='0.7'))
 expect_true(d$dirty);expect_identical(d$committed,s$committed);expect_false(s$dirty)
 d<-.ig_workbench_preview(d,analysis_envelope(b,rb))
 expect_identical(d$committed$spec_hash,a$spec_hash)
 applied<-.ig_workbench_apply_preview(d)
 expect_identical(applied$committed$spec_hash,b$spec_hash)
 expect_identical(applied$committed$result_hash,rb$result_hash)
 expect_false(applied$dirty);expect_null(applied$preview);expect_null(applied$pending)
})
test_that('stale, foreign-session and wrong-spec responses cannot replace a result',{
 s<-.ig_workbench_new(a,'session-one');ticket<-s$pending
 t<-.ig_workbench_commit(s,b)
 expect_identical(.ig_workbench_accept(t,ticket,ra),t)
 foreign<-.ig_workbench_new(b,'session-two')$pending
 expect_identical(.ig_workbench_accept(t,foreign,rb),t)
 expect_identical(.ig_workbench_accept(t,t$pending,ra),t)
 accepted<-.ig_workbench_accept(t,t$pending,rb)
 expect_identical(accepted$committed$result_hash,rb$result_hash)
 expect_identical(.ig_workbench_accept(accepted,ticket,ra),accepted)
})
test_that('undo and redo restore complete states and invalidate pending work',{
 s<-.ig_workbench_new(a,'s');s<-.ig_workbench_accept(s,s$pending,ra)
 s<-.ig_workbench_commit(s,b);old<-s$pending
 u<-.ig_workbench_history(s,-1)
 expect_identical(u$committed$result_hash,ra$result_hash);expect_null(u$pending)
 expect_identical(.ig_workbench_accept(u,old,rb),u)
 r<-.ig_workbench_history(u,1)
 expect_identical(r$committed$spec_hash,b$spec_hash);expect_false(identical(r$pending,old))
 r<-.ig_workbench_accept(r,r$pending,rb)
 expect_identical(r$committed$result_hash,rb$result_hash)
 changed<-.ig_workbench_commit(u,spec(.9))
 expect_identical(.ig_workbench_history(changed,1),changed)
})
test_that('locale and bounded history preserve numerical identity',{
 s<-.ig_workbench_new(a,'s',history_limit=2L)
 d<-.ig_workbench_locale(s,'de');expect_identical(d$committed,s$committed)
 expect_identical(d$pending,s$pending)
 for(x in c(.6,.7,.8)) d<-.ig_workbench_commit(d,spec(x))
 expect_length(d$history,2);expect_equal(d$cursor,2)
 expect_error(.ig_workbench_locale(d,'xx'),class='inferguidR_invalid_input')
})
test_that('classification envelopes share the same state transitions without power conversion',{
 cs<-classification_spec(counts=c(tp=30,fn=10,fp=15,tn=145),cutoff=.4)
 cr<-evaluate_cutoff(cs)
 s<-.ig_workbench_new(cs,'classifier');s<-.ig_workbench_accept(s,s$pending,cr)
 expect_identical(s$committed$analysis_kind,'classification')
 expect_identical(s$committed$spec_hash,cs$spec_hash)
 expect_error(.ig_workbench_preview(s,analysis_envelope(a,ra)),class='inferguidR_invalid_input')
})
