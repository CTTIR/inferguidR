test_that("classification rendering retains canonical model and decision-set data", {
  skip_if_not_installed("ggplot2")
  r <- evaluate_cutoff(classification_examples("scored_synthetic")$spec)
  p <- plot_classification(r, "roc", "model_b")
  pd <- classification_plot_data(r, "roc", "model_b")
  expect_identical(attr(p, "inferguidR_plot_data"), pd)
  b <- ggplot2::ggplot_build(p)
  expect_equal(b$data[[1]]$x, pd$data$points$fpr)
  expect_equal(b$data[[1]]$y, pd$data$points$tpr)
  expect_true(any(pd$data$points$segment_from_previous == "tie_diagonal", na.rm = TRUE))
  expect_equal(tail(b$data, 1)[[1]]$x, pd$data$current$fpr)
  expect_equal(tail(b$data, 1)[[1]]$y, pd$data$current$tpr)
  expect_error(plot_classification(r, model_id = "absent"), "not a model")
})

test_that("precision-recall is rendered as attained points without interpolation", {
  skip_if_not_installed("ggplot2")
  r <- evaluate_cutoff(classification_examples("scored_synthetic")$spec)
  p <- plot_classification(r, "pr", lang = "de")
  pd <- attr(p, "inferguidR_plot_data")
  expect_true(inherits(p$layers[[1]]$geom,"GeomPoint"))
  paths<-Filter(function(l) inherits(l$geom,"GeomPath"),p$layers)
  expect_true(all(vapply(paths,function(l) "f1_level" %in% names(l$data),TRUE)))
  b <- ggplot2::ggplot_build(p)
  expect_equal(b$data[[1]]$x, pd$data$points$recall)
  expect_equal(b$data[[1]]$y, pd$data$points$precision)
  expect_equal(b$data[[2]]$yintercept, .3)
  expect_match(p$labels$caption, "Keine lineare Interpolation")
  expect_true(pd$data$excluded$n_zero_alert_points > 0)
})

test_that("fixed counts cannot manufacture ROC or precision-recall curves", {
  skip_if_not_installed("ggplot2")
  r <- evaluate_cutoff(classification_examples("counts_fixed")$spec)
  expect_error(plot_classification(r, "roc"))
  expect_error(plot_classification(r, "pr"))
})

test_that("scenario precision and reference prevalence are explicit in rendering", {
  skip_if_not_installed("ggplot2")
  spec <- update(classification_examples("scored_synthetic")$spec, prevalence = .05)
  r <- evaluate_cutoff(spec)
  p <- plot_classification(r, "pr", basis = "scenario")
  pd <- classification_plot_data(r, "pr", basis = "scenario")
  expect_identical(attr(p, "inferguidR_plot_data"), pd)
  expect_equal(ggplot2::ggplot_build(p)$data[[2]]$yintercept, .05)
  expect_match(p$labels$caption, "scenario_assumed")
  expect_identical(attr(plot_classification(r, "roc", basis = "scenario"), "inferguidR_plot_data")$data$points,
                   classification_plot_data(r, "roc")$data$points)
})
