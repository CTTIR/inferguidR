testthat::test_that("additional panels retain geometry and basis semantics", {
 testthat::skip_if_not_installed("ggplot2")
 r <- evaluate_cutoff(update(classification_examples("scored_synthetic")$spec, prevalence = .05))
 draw <- function(panel, mode = "joint") .ig_plot_classification_additional(r, panel, "model_b", "scenario", "en", mode, 40)
 joint <- draw("mosaic")
 d <- joint$data
 testthat::expect_equal(sum((d$x1-d$x0)*(d$y1-d$y0)), 1)
 testthat::expect_equal((d$x1-d$x0)*(d$y1-d$y0), d$area_share)
 cond <- draw("mosaic", "within_class")
 testthat::expect_true(all(is.na(cond$data$area_share)))
 testthat::expect_true(all(cond$data$x1-cond$data$x0 == .5))
 testthat::expect_match(cond$labels$caption, "not joint")
 dist <- draw("score_distribution")
 testthat::expect_identical(attr(dist,"inferguidR_plot_data")$basis,"observed")
 testthat::expect_equal(as.numeric(tapply(dist$data$value,dist$data$class,sum)),c(1,1))
 pv <- draw("prevalence_curve")
 source <- attr(pv,"inferguidR_plot_data")$data$curve
 testthat::expect_equal(pv$data$value[pv$data$metric=="PPV"],source$ppv)
 testthat::expect_equal(pv$data$value[pv$data$metric=="NPV"],source$npv)
 comp <- draw("model_comparison")
 testthat::expect_equal(length(unique(comp$data$model)),2)
 testthat::expect_identical(attr(comp,"inferguidR_plot_data")$basis,"observed")
 for(p in list(joint,cond,dist,pv,comp)) testthat::expect_silent(ggplot2::ggplot_build(p))
})
testthat::test_that("binormal density uses analytical plot data and fixed counts support a mosaic", {
 testthat::skip_if_not_installed("ggplot2")
 b <- evaluate_cutoff(classification_examples("binormal_equal_variance")$spec)
 p <- .ig_plot_classification_additional(b,"score_distribution",NULL,"observed","de","joint",40)
 testthat::expect_equal(p$data$value[p$data$class=="event"],attr(p,"inferguidR_plot_data")$data$densities$density_events)
 testthat::expect_silent(ggplot2::ggplot_build(p))
 c <- evaluate_cutoff(classification_examples("counts_fixed")$spec)
 p <- .ig_plot_classification_additional(c,"mosaic",NULL,"observed","en","joint",40)
 testthat::expect_equal(p$data$area_share,c(.2,.05,.1,.65))
})


testthat::test_that("public panel dispatch validates controls and preserves its data", {
 testthat::skip_if_not_installed("ggplot2")
 r <- evaluate_cutoff(classification_examples("counts_fixed")$spec)
 p <- plot_classification(r, "mosaic", mosaic_mode = "within_class")
 testthat::expect_identical(attr(p, "inferguidR_plot_data"), classification_plot_data(r, "mosaic"))
 testthat::expect_error(plot_classification(r, "mosaic", mosaic_mode = "absent"))
 s <- evaluate_cutoff(classification_examples("scored_synthetic")$spec)
 testthat::expect_error(plot_classification(s, "score_distribution", bins = 1), "whole number")
})
